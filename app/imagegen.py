from __future__ import annotations

import asyncio
import base64
import logging
import random
import time
import urllib.parse
from pathlib import Path

import httpx

log = logging.getLogger(__name__)

POLLINATIONS_URL = "https://image.pollinations.ai/prompt/"
POLLINATIONS_ATTEMPTS = 4
OPENROUTER_CHAT_URL = "https://openrouter.ai/api/v1/chat/completions"


class ImageGenerationError(RuntimeError):
    pass


async def _from_pollinations(prompt: str, transport: httpx.AsyncBaseTransport | None = None) -> bytes:
    url = POLLINATIONS_URL + urllib.parse.quote(prompt, safe="")
    params = {"width": 1024, "height": 1024, "nologo": "true", "seed": random.randint(1, 10**9)}
    reason = "pollinations:unknown"
    async with httpx.AsyncClient(timeout=180, transport=transport) as client:
        for attempt in range(POLLINATIONS_ATTEMPTS):
            try:
                response = await client.get(url, params=params)
                if response.status_code == 200 and response.headers.get("content-type", "").startswith("image/"):
                    return response.content
                reason = f"pollinations:{response.status_code}"
            except Exception as exc:
                reason = f"pollinations:{str(exc)[:80]}"
            await asyncio.sleep(2 + attempt)
    raise ImageGenerationError(reason)


async def _from_openrouter(prompt: str, settings, transport: httpx.AsyncBaseTransport | None = None) -> bytes:
    headers = {"Authorization": f"Bearer {settings.openrouter_api_key}", "Content-Type": "application/json"}
    body = {"model": settings.image_model, "modalities": ["image", "text"], "messages": [{"role": "user", "content": prompt}]}
    async with httpx.AsyncClient(timeout=180, transport=transport) as client:
        response = await client.post(OPENROUTER_CHAT_URL, headers=headers, json=body)
        response.raise_for_status()
        message = ((response.json().get("choices") or [{}])[0].get("message") or {})
        for item in message.get("images") or []:
            url = (item.get("image_url") or {}).get("url") or ""
            if url.startswith("data:image"):
                return base64.b64decode(url.split(",", 1)[1])
    raise ImageGenerationError("openrouter:no-image")


async def generate_image(prompt: str, settings, transport: httpx.AsyncBaseTransport | None = None) -> bytes:
    """Free generation first; a configured paid image model is only a fallback."""
    try:
        return await _from_pollinations(prompt, transport)
    except Exception:
        log.warning("Pollinations image generation failed", exc_info=True)
        if not settings.image_model:
            raise
    return await _from_openrouter(prompt, settings, transport)


def save_image(data: bytes, settings) -> Path:
    """Persist generated bytes with a suffix that matches the payload's magic bytes."""
    directory = settings.data_dir / "generated"
    directory.mkdir(parents=True, exist_ok=True)
    suffix = ".jpg" if data[:2] == b"\xff\xd8" else ".png"
    path = directory / f"image-{int(time.time())}-{random.randrange(16**6):06x}{suffix}"
    path.write_bytes(data)
    return path
